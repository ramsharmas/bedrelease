import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
"""Train + evaluate on SYNTHETIC in-stay data. Split by patient. Writes outputs/synthetic_metrics.json"""
import json, numpy as np, pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score, accuracy_score, precision_score, recall_score, f1_score
from bedrelease import synthetic as S
from bedrelease import data
c = data.load_clean(); df = c.df if hasattr(c, "df") else c[0]
r = S.make(df[["patient_nbr", "los", "age", "admission_type", "diag_group"]])
feats = [f for f in S.SIGNALS if f != "frac_stay_done"]
pid = r["patient_nbr"].astype(str) + "_" + r["copy"].astype(str)
u = pid.unique(); rng = np.random.default_rng(1); rng.shuffle(u)
cut1, cut2 = int(.7 * len(u)), int(.85 * len(u))
part = pd.Series("test", index=u); part[u[:cut1]] = "train"; part[u[cut1:cut2]] = "valid"
r["part"] = pid.map(part).values
tr, va, te = (r[r.part == k] for k in ("train", "valid", "test"))
m = HistGradientBoostingClassifier(max_iter=300, learning_rate=0.08, random_state=1).fit(tr[feats], tr.label)
pv = m.predict_proba(va[feats])[:, 1]
grid = np.linspace(.05, .95, 91); thr = float(grid[np.argmax([accuracy_score(va.label, pv >= t) for t in grid])])
p = m.predict_proba(te[feats])[:, 1]; yh = (p >= thr).astype(int); y = te.label.to_numpy()
lr = LogisticRegression(max_iter=500).fit(tr[feats], tr.label); pl = lr.predict_proba(te[feats])[:, 1]
no_plan = HistGradientBoostingClassifier(max_iter=300, random_state=1).fit(tr[[f for f in feats if f != "doctor_plan_tomorrow"]], tr.label)
pn = no_plan.predict_proba(te[[f for f in feats if f != "doctor_plan_tomorrow"]])[:, 1]
out = {"WARNING": "SYNTHETIC in-stay signals generated by bedrelease/synthetic.py; accuracy reflects the simulator, not a real hospital",
       "rows": {"train": len(tr), "valid": len(va), "test": len(te)}, "positive_rate_pct": float(y.mean() * 100),
       "threshold_from_validation": thr, "accuracy": float(accuracy_score(y, yh)), "precision": float(precision_score(y, yh)),
       "recall": float(recall_score(y, yh)), "f1": float(f1_score(y, yh)), "roc_auc": float(roc_auc_score(y, p)),
       "majority_class_accuracy": float(1 - y.mean()),
       "logistic_regression_roc_auc": float(roc_auc_score(y, pl)),
       "ablation_without_doctor_plan_roc_auc": float(roc_auc_score(y, pn)),
       "accuracy_without_doctor_plan": float(accuracy_score(y, pn >= .5)),
       "feature_list": feats}
json.dump(out, open("outputs/synthetic_metrics.json", "w"), indent=1); print(json.dumps(out, indent=1))
import joblib; joblib.dump({"model": m, "features": feats, "threshold": thr}, "outputs/synthetic_model.joblib")
te.assign(p=p)[feats + ["label", "p"]].sample(20000, random_state=1).to_csv("outputs/synthetic_test_sample.csv.gz", index=False)
